- 다만 수탁자인 Supabase, Inc. 는 미국에 소재한 법인으로, 시스템 운영 및 기술 지원
  과정에서 국외에서 해당 데이터에 접근할 가능성이 있습니다.
- AI 기능을 사용하는 경우, 아래와 같이 개인정보가 국외로 이전됩니다.
  · 이전받는 자: Google LLC (미국)
  · 이전 국가: 미국
  · 이전 일시 및 방법: 트레이너가 AI 초안 생성을 요청하는 시점에 암호화된 통신
    (HTTPS)으로 전송
  · 이전 항목: 이름을 마스킹 처리한 수업 기록 요약, 운동 목적, 신체 측정값 요약
    (사진·영상은 이전하지 않습니다)
  · 이전받는 자의 이용 목적 및 보유 기간: 요청한 문장 초안 생성, 목적 달성 즉시
- 회원은 국외 이전을 거부할 수 있습니다. [설정 > AI 사용]에서 거부하면 해당 회원의
  정보는 국외로 전송되지 않으며, 트레이너는 기본 템플릿과 직접 입력으로 동일한
