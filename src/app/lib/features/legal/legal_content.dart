  (1) 담당 트레이너가 회원의 동의를 확인하여 등록하고,
  (2) 회원 본인이 앱에서 거부하지 않은 경우
- 회원은 [설정 > AI 사용]에서 현재 상태를 확인하고 언제든 거부할 수 있습니다.
  회원이 거부하면 트레이너가 이를 되돌릴 수 없으며, 즉시 전달이 중단됩니다.

