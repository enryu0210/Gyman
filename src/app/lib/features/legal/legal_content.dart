/// 약관/정책 문서 종류.
enum LegalDoc {
  terms,
  privacy,
}

extension LegalDocInfo on LegalDoc {
  /// 화면 제목.
  String get title {
    switch (this) {
      case LegalDoc.terms:
        return '이용약관';
      case LegalDoc.privacy:
        return '개인정보 처리방침';
    }
  }

  /// 라우트 경로.
  String get route {
    switch (this) {
      case LegalDoc.terms:
        return '/legal/terms';
      case LegalDoc.privacy:
        return '/legal/privacy';
    }
  }

  /// 본문(마크다운 아님 — 단순 텍스트 단락).
  String get body {
    switch (this) {
      case LegalDoc.terms:
        return _terms;
      case LegalDoc.privacy:
        return _privacy;
    }
  }
}

